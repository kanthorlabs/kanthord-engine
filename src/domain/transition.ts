const lookup = new Map<string, TransitionRow>(
  transitions.map((row) => [`${row.from}->${row.to}`, row]),
);

export function canTransition(
  level: NodeKind,
  from: NodeState,
  to: NodeState,
): boolean {
  if (from === to) return false;
  const row = lookup.get(`${from}->${to}`);
  return row ? row[level] : false;
}
